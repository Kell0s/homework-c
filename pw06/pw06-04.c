#include <stdio.h>

int main(void) {
    double i;
    int r;
    int c;

    printf("Введите объём (ГБ): ");

    while ((r = scanf("%lf", &i)) != EOF) {
        if (r != 1) {
            printf("Вы указали не число\n");
            while ((c = getchar()) != '\n' && c != EOF) {
            }
        } else if (i < 0) {
            printf("Вы указали меньше 0\n");
        } else if (i <= 10) {
            printf("Объём: %.2f ГБ\n"
                   "До 10 ГБ: %.2f x 1.0 = %.2f\n"
                   "Итого: %.2f\n",
                   i, i, i * 1.0, i * 1.0);
        } else if (i <= 60) {
            printf("Объём: %.2f ГБ\n"
                   "До 10 ГБ: %.2f x 1.0 = %.2f\n"
                   "От 10 до 60: %.2f x 0.8 = %.2f\n"
                   "Итого: %.2f\n",
                   i, 10.0, 10.0, i - 10, (i - 10) * 0.8, 10.0 + (i - 10) * 0.8);
        } else {
            printf("Объём: %.2f ГБ\n"
                   "До 10 ГБ: %.2f x 1.0 = %.2f\n"
                   "От 10 до 60: %.2f x 0.8 = %.2f\n"
                   "Свыше 60: %.2f x 0.5 = %.2f\n"
                   "Итого: %.2f\n",
                   i, 10.0, 10.0, 50.0, 40.0, i - 60, (i - 60) * 0.5, 10.0 + 40.0 + (i - 60) * 0.5);
        }

        printf("Введите объём (ГБ): ");
    }

    printf("\n");
    return 0;
}

